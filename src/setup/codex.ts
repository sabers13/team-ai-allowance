/**
 * Codex managed configuration.
 *
 * `/etc/codex/requirements.toml` is enforced and cannot be overridden: it
 * holds the MCP server allowlist and any approval/sandbox guardrails.
 * `/etc/codex/managed_config.toml` supplies startup defaults (gateway
 * provider, default model, the `taa` MCP server) and overrides the user's
 * `config.toml` at startup, although a user can change values during a run.
 *
 * The key is named by `env_key`; it is never written here.
 */

import { openAiBaseUrl } from "./spec.ts";
import type { SetupSpec } from "./types.ts";

/** A TOML basic string. Inputs are validated, but escape anyway. */
export function tomlString(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n")}"`;
}

function tomlArray(values: readonly string[]): string {
  return `[${values.map(tomlString).join(", ")}]`;
}

export function codexRequirements(spec: SetupSpec): string {
  const lines = [
    "# Generated by team-ai-allowance setup. Enforced in Codex; users cannot override it.",
    "# MCP servers are an allowlist: only the servers below can be enabled.",
  ];
  if (spec.team.security.allowedApprovalPolicies !== undefined) {
    lines.push(
      `allowed_approval_policies = ${tomlArray(spec.team.security.allowedApprovalPolicies)}`,
    );
  }
  if (spec.team.security.allowedSandboxModes !== undefined) {
    lines.push(`allowed_sandbox_modes = ${tomlArray(spec.team.security.allowedSandboxModes)}`);
  }
  lines.push(
    "",
    "# The request desk. Matching is on the executable only; args and env are not inspected.",
    "[mcp_servers.taa]",
    `identity = { command = ${tomlString(spec.team.mcp.command)} }`,
    "",
  );
  return lines.join("\n");
}

export function codexManagedConfig(spec: SetupSpec): string {
  const lines = [
    "# Generated by team-ai-allowance setup. Startup defaults; the gateway key is in the member env.",
    `model = ${tomlString(spec.team.defaultModel)}`,
    `model_provider = ${tomlString(spec.team.providerId)}`,
    "",
    `[model_providers.${spec.team.providerId}]`,
    `name = ${tomlString(`Team gateway (${spec.team.name})`)}`,
    `base_url = ${tomlString(openAiBaseUrl(spec.team.gatewayUrl))}`,
    'env_key = "TAA_MEMBER_KEY"',
    'wire_api = "responses"',
    "",
    "# The request desk. The member key is inherited from the process environment.",
    "[mcp_servers.taa]",
    `command = ${tomlString(spec.team.mcp.command)}`,
    `args = ${tomlArray(spec.team.mcp.args)}`,
    "",
  ];
  return lines.join("\n");
}
