/**
 * Enrolment bundle stub.
 *
 * The setup module (`src/setup/`) owns the full per-CLI generators. This helper returns a
 * clearly-labelled placeholder bundle with the same shape. The bundle never
 * carries the member key: the key is shown once at creation.
 */

import type { Clock, Member } from "../contracts.ts";
import type { ConfigBundle } from "./control.ts";

export function stubConfigBundle(member: Member, clock: Clock): ConfigBundle {
  const at = clock.now().toISOString();
  return {
    memberId: member.id,
    teamId: member.teamId,
    generatedAt: at,
    generator: "stub",
    note: "Per-CLI enrolment bundle. No key is included; the key was shown once when the member was created.",
    files: [
      {
        path: "claude-code/managed-settings.json",
        content: `${JSON.stringify({ note: "generated by team-ai-allowance", member: member.id }, null, 2)}\n`,
      },
      {
        path: "opencode/opencode.json",
        content: `${JSON.stringify({ note: "generated by team-ai-allowance", member: member.id }, null, 2)}\n`,
      },
      {
        path: "codex/config.toml",
        content: `# generated by team-ai-allowance\n# member = "${member.id}"\n`,
      },
      {
        path: "env/taa.env",
        content:
          "# The member key is shown once at creation and is never part of this bundle.\nTAA_MEMBER_KEY=\n",
      },
    ],
  };
}
