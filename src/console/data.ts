/**
 * The data boundary of the console.
 *
 * The console consumes the control-service shapes
 * through `ConsoleData` and calls mutations through
 * `ConsoleActions`, so the pages never reach into the store or the gateway.
 * `fixtures.ts` implements both during Wave 1 and the tests run against it.
 */

import type {
  AuditEvent,
  Decision,
  DecisionOutcome,
  EffectivePolicy,
  Grant,
  IsoDateTime,
  Limits,
  Member,
  MemberId,
  ModelEntry,
  Notification,
  Period,
  Request,
  RequestState,
  Role,
  Rule,
  Team,
  TeamPolicy,
  UsageRow,
} from "../contracts.ts";
import type { UsageQuery, UsageReport } from "./usage/index.ts";

export type Theme = "system" | "light" | "dark";

/** The page shell context, re-exported so pages import from one place. */
export type { PageContext } from "./layout.ts";

export type ListMode = "ready" | "loading" | "empty" | "error";

export interface Viewer {
  role: Role;
  displayName: string;
  teamId: string;
  teamName: string;
  /** Present when the viewer is also a member with an allowance. */
  memberId: MemberId | null;
  csrfToken: string;
  email: string | null;
}

export interface ConsoleSession {
  viewer: Viewer;
}

export interface OverviewMemberRow {
  member: Member;
  policy: EffectivePolicy;
  /** Spend inside the member's own budget period. */
  spendUsd: number;
  /** Spend over the last 30 days, for the team total. */
  monthSpendUsd: number;
}

export interface ModelSpend {
  modelId: string;
  modelName: string;
  spendUsd: number;
  requests: number;
}

export interface OverviewData {
  team: Team;
  teamPolicy: TeamPolicy;
  members: OverviewMemberRow[];
  models: ModelEntry[];
  openRequests: Request[];
  alerts: Notification[];
  spendByModel: ModelSpend[];
  teamSpendUsd: number;
  periodLabel: string;
  periodEndsAt: IsoDateTime;
}

export interface RequestListFilter {
  state: RequestState | "all";
  view: "inbox" | "history";
  memberId: MemberId | null;
  query: string;
  limit: number;
}

export interface RequestDetail {
  request: Request;
  member: Member;
  decisions: Decision[];
  /** A cheaper enabled model that would serve the same job, when known. */
  hint: string | null;
}

export interface MemberDetail {
  member: Member;
  team: Team;
  policy: EffectivePolicy;
  limits: Limits;
  /** The member's own model selection, before grants are added. */
  selectedModelIds: string[];
  /** Spend inside the member's own budget period. */
  spendUsd: number;
  grants: Grant[];
  usage: UsageRow[];
  audit: AuditEvent[];
  keyState: {
    active: boolean;
    blocked: boolean;
    /** The effective policy status, which also covers watcher blocks. */
    status: EffectivePolicy["status"];
    reason: string | null;
    lastRotatedAt: IsoDateTime | null;
  };
}

export interface ModelRow {
  model: ModelEntry;
  requestsLast30Days: number;
  membersAllowed: number;
}

export interface ModelsData {
  models: ModelRow[];
}

export interface DoctorReport {
  id: string;
  memberId: MemberId;
  cli: "claude-code" | "opencode" | "codex";
  version: string;
  gatewayOk: boolean;
  mcpOk: boolean;
  managedConfig: boolean;
  at: IsoDateTime;
  notes: string[];
}

export interface SetupMemberRow {
  member: Member;
  policy: EffectivePolicy;
  spendUsd: number;
  reports: DoctorReport[];
}

export interface SetupData {
  team: Team;
  members: SetupMemberRow[];
  gatewayHealthy: boolean;
  gatewayCheckedAt: IsoDateTime;
  /** The managed-config pack version generated by the setup module. */
  packVersion: string | null;
  packFiles: string[];
}

export interface MyData {
  member: Member;
  team: Team;
  policy: EffectivePolicy;
  spendUsd: number;
  requests: Request[];
  usage: UsageRow[];
  allowedModels: ModelEntry[];
  resetAt: IsoDateTime;
}

export interface BundleFile {
  filename: string;
  contentType: string;
  body: string;
}

export interface PageSort {
  key: "name" | "spend" | "used" | "status";
  direction: "asc" | "desc";
}

export interface ConsoleData {
  overview(sort: PageSort): Promise<OverviewData>;
  members(): Promise<Member[]>;
  requests(filter: RequestListFilter): Promise<Request[]>;
  requestCounts(): Promise<{ inbox: number; history: number }>;
  requestDetail(id: string): Promise<RequestDetail | null>;
  memberDetail(id: string): Promise<MemberDetail | null>;
  models(): Promise<ModelsData>;
  rules(): Promise<{ rules: Rule[]; policy: TeamPolicy }>;
  audit(filter: {
    actorId: string | null;
    objectType: string | null;
    objectId: string | null;
    from: string | null;
    to: string | null;
    limit: number;
    offset: number;
  }): Promise<AuditEvent[]>;
  auditActors(): Promise<Array<{ id: string; name: string }>>;
  setup(): Promise<SetupData>;
  me(viewer: Viewer): Promise<MyData | null>;
  /** Manager and admin usage report for a period. Members never call it. */
  usage(query: UsageQuery): Promise<UsageReport>;
  openRequestCount(): Promise<number>;
  bundle(memberId: MemberId): Promise<BundleFile | null>;
  modelCatalogue(): Promise<ModelEntry[]>;
}

export interface DecideInput {
  outcome: DecisionOutcome;
  note: string | null;
  amountUsd: number | null;
  modelId: string | null;
  until: string | null;
  permanent: boolean;
}

export interface LimitsInput {
  budgetUsd: number;
  period: Period;
  tokenCap: number | null;
  rpm: number | null;
  tpm: number | null;
}

export interface EnrolInput {
  displayName: string;
  email: string | null;
  role: Role;
  budgetUsd: number;
  period: Period;
}

export interface ActionReceipt {
  message: string;
  /** Present once, on enrolment and key rotation. */
  secret: string | null;
  memberId: MemberId | null;
}

export interface ConsoleActions {
  decide(requestId: string, input: DecideInput): Promise<ActionReceipt>;
  updateLimits(memberId: MemberId, input: LimitsInput): Promise<ActionReceipt>;
  updateModels(memberId: MemberId, modelIds: string[]): Promise<ActionReceipt>;
  keyAction(
    memberId: MemberId,
    action: "block" | "unblock" | "rotate",
    reason: string | null,
  ): Promise<ActionReceipt>;
  saveRule(rule: Rule): Promise<ActionReceipt>;
  savePolicy(policy: TeamPolicy): Promise<ActionReceipt>;
  createRequest(input: {
    kind: "more_budget" | "model_unlock" | "suggestion";
    amountUsd: number | null;
    modelId: string | null;
    message: string;
  }): Promise<ActionReceipt>;
  cancelRequest(requestId: string): Promise<ActionReceipt>;
  revokeGrant(memberId: MemberId, grantId: string, reason: string): Promise<ActionReceipt>;
  enrolMember(input: EnrolInput): Promise<ActionReceipt>;
}

export interface LoginResult {
  ok: boolean;
  message: string | null;
  /** The `Set-Cookie` value for the session when the login succeeded. */
  cookie: string | null;
  /** The signed-in person, when the credential matched. */
  viewer: Viewer | null;
  /** HTTP status for a failure; 401 unless the attempt was rate-limited. */
  status?: number;
}

export interface LoginAttempt {
  email: string;
  password: string;
  /** A member gateway key; members have no password. */
  memberKey: string;
  /** The client address, for the per-IP failure limiter. */
  ip: string;
}

export interface ConsoleAuth {
  login(attempt: LoginAttempt): Promise<LoginResult>;
  logout(): string;
}

export class ConsoleActionError extends Error {
  readonly status: number;

  constructor(message: string, status = 422) {
    super(message);
    this.name = "ConsoleActionError";
    this.status = status;
  }
}
