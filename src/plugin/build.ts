/**
 * Build the drop-in OpenCode plugin file.
 *
 * The source is already a single self-contained module; the build copies it to
 * `dist/plugin/team-ai-allowance.ts` with a generated banner and refuses to
 * emit a file that imports a runtime package. Node built-ins are allowed
 * because state-on-disk and the HTTP client need them.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

export const SOURCE_PATH = fileURLToPath(new URL("./team-ai-allowance.ts", import.meta.url));
export const OUTPUT_PATH = fileURLToPath(
  new URL("../../dist/plugin/team-ai-allowance.ts", import.meta.url),
);

export const BANNER = `// Generated by src/plugin/build.ts from src/plugin/team-ai-allowance.ts.
// Do not edit this copy. Self-contained: runtime imports are Node built-ins only.
`;

/** Reject anything that would need an install beside the drop-in file. */
export function assertSelfContained(source: string): void {
  for (const match of source.matchAll(/^\s*import\s+[^;]*?from\s+["']([^"']+)["']/gm)) {
    const specifier = match[1] ?? "";
    if (!specifier.startsWith("node:")) {
      throw new Error(`built plugin must not import ${specifier}`);
    }
  }
  if (/^\s*(?:const|let|var)\s+[^=]*=\s*require\(/m.test(source)) {
    throw new Error("built plugin must not call require()");
  }
  if (/(?:^|[^\w.])eval\s*\(/m.test(source)) {
    throw new Error("built plugin must not call eval()");
  }
}

export function buildPlugin(): string {
  const source = readFileSync(SOURCE_PATH, "utf8");
  assertSelfContained(source);
  const output = `${BANNER}\n${source}`;
  mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
  writeFileSync(OUTPUT_PATH, output, "utf8");
  return output;
}

const invokedDirectly =
  process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1];

if (invokedDirectly) {
  buildPlugin();
  process.stdout.write(`wrote ${OUTPUT_PATH}\n`);
}
