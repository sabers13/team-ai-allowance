/**
 * `make demo`: seed the demo organisation and serve it.
 *
 * It starts the gateway mock from `e2e/flow/fake-gateway.ts` (unless
 * `TAA_GATEWAY_URL` points at a real stack), starts `taa serve` in this
 * process, and prints where the console is. One-time secrets — the manager
 * password, the manager token and each member's gateway key — go to
 * `var/demo-credentials.txt` with mode 0600; they are never printed and never
 * committed. `var/` is ignored by git.
 *
 * The gateway mock charges a fixed USD 0.30 per model call, so the demo's
 * budgets mean a handful of calls rather than a hundred thousand.
 */

import { randomBytes } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

import { type FakeGateway, startFakeGateway } from "../e2e/flow/fake-gateway.ts";
import { createControlServer, loadServerConfig } from "../src/server/index.ts";

const DEMO_MANAGER_EMAIL = "priya@example.test";
/** Generated per run unless the caller supplies one; written to the 0600 file. */
const DEMO_MANAGER_PASSWORD =
  process.env.TAA_DEMO_MANAGER_PASSWORD ?? randomBytes(12).toString("base64url");
const PORT = process.env.TAA_PORT ?? "18080";
const CREDENTIALS_FILE = resolve(
  process.env.TAA_DEMO_CREDENTIALS_FILE ?? "var/demo-credentials.txt",
);
const DB_PATH = resolve(process.env.TAA_DB_PATH ?? "var/demo.db");

const env: NodeJS.ProcessEnv = {
  ...process.env,
  TAA_PORT: PORT,
  TAA_DB_PATH: DB_PATH,
  TAA_DEV_SECRETS: process.env.TAA_DEV_SECRETS ?? "1",
  TAA_DEMO_SEED: "1",
  TAA_DEMO_MANAGER_PASSWORD: DEMO_MANAGER_PASSWORD,
  TAA_WATCH_INTERVAL_MS: process.env.TAA_WATCH_INTERVAL_MS ?? "2000",
  TAA_RECONCILE_INTERVAL_MS: process.env.TAA_RECONCILE_INTERVAL_MS ?? "5000",
  TAA_HINTS_FILE: process.env.TAA_HINTS_FILE ?? resolve("config/model-hints.json"),
  TAA_PUBLIC_URL: process.env.TAA_PUBLIC_URL ?? `http://127.0.0.1:${PORT}`,
};

let fake: FakeGateway | null = null;
if (process.env.TAA_GATEWAY_URL === undefined) {
  fake = await startFakeGateway({
    port: Number.parseInt(process.env.TAA_MOCK_GATEWAY_PORT ?? "18091", 10),
  });
  env.TAA_GATEWAY_URL = fake.url;
  env.LITELLM_MASTER_KEY = process.env.LITELLM_MASTER_KEY ?? "sk-demo-master";
}

const config = loadServerConfig({ env });
const server = await createControlServer({ config, env });
await server.start();

const demo = server.demo;
if (demo === null) {
  process.stderr.write("demo: the demo seed did not run\n");
  await server.stop();
  process.exit(1);
}

const lines = [
  "# Team AI Allowance demo credentials",
  "# Generated by scripts/demo.ts. Mode 0600. Never commit or share this file.",
  "# Every value here was shown once, at creation.",
  "",
  `console        ${config.publicUrl}`,
  `manager email  ${DEMO_MANAGER_EMAIL}`,
  `manager pass   ${DEMO_MANAGER_PASSWORD}`,
  `manager token  ${demo.managerToken ?? "(not issued this run)"}`,
  "",
  ...demo.keys.map(
    (key) => `${key.displayName.padEnd(14)} ${key.memberId}  TAA_MEMBER_KEY=${key.secret}`,
  ),
  "",
];
await mkdir(dirname(CREDENTIALS_FILE), { recursive: true });
await writeFile(CREDENTIALS_FILE, `${lines.join("\n")}\n`, { mode: 0o600 });

process.stdout.write(
  [
    `demo: console      ${config.publicUrl}`,
    `demo: health       ${config.publicUrl}/health`,
    `demo: database     ${config.dbPath}`,
    `demo: credentials  ${CREDENTIALS_FILE} (mode 600; not printed)`,
    fake === null
      ? "demo: gateway      real stack from TAA_GATEWAY_URL"
      : `demo: gateway mock ${fake.url} (USD 0.30 per call)`,
    "",
    "Sign in as priya@example.test with the password in the credentials file.",
    "Press Ctrl-C to stop.",
  ].join("\n") + "\n",
);

const shutdown = async (): Promise<void> => {
  await server.stop();
  if (fake !== null) await fake.close();
  process.exit(0);
};
process.once("SIGINT", () => void shutdown());
process.once("SIGTERM", () => void shutdown());
